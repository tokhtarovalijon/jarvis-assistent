def check_homework(user_text):
    """Студент рассказывает своими словами задачу и своё решение — Джарвис проверяет
    логику рассуждения, а не просто выдаёт готовый ответ вместо него."""
    if not client:
        return "ИИ-модуль не настроен, не могу проверить, сэр."
    try:
        response = client.chat.completions.create(
            model="openai/gpt-oss-20b",
            messages=[
                {
                    "role": "system",
                    "content": (
                        f"Ты — {BOT_NAME}, преподаватель, проверяющий домашнее задание студента "
                        "экономического университета. Студент опишет задачу и своё решение "
                        "своими словами в устной форме. Проверь ЛОГИКУ рассуждения и расчёт:\n"
                        "1) Если решение верное — подтверди и похвали кратко.\n"
                        "2) Если есть ошибка — укажи, на каком именно шаге и в чём именно "
                        "ошибка. НЕ давай сразу готовый правильный ответ — подтолкни студента "
                        "исправить самостоятельно наводящим вопросом или указанием направления.\n"
                        "3) Если не хватает данных, чтобы понять решение — попроси уточнить, "
                        "что именно было в условии.\n"
                        "Отвечай по-дружески, как наставник, 3-6 предложений."
                    ),
                },
                {"role": "user", "content": user_text},
            ],
            temperature=0.3,
            max_tokens=800,
        )
        return response.choices[0].message.content
    except Exception as e:
        print(f"[Ошибка проверки ДЗ] {e}")
        return "Не удалось проверить решение, сэр."