# --- ПОИСК В ИНТЕРНЕТЕ (DuckDuckGo, бесплатно, без ключа) ---
SEARCH_TRIGGERS = [
    "найди в интернете", "поищи в интернете", "загугли", "погугли",
    "актуальные данные по", "что нового про",
]


def is_search_request(text):
    return any(trigger in text for trigger in SEARCH_TRIGGERS)


def web_search(query, max_results=4):
    """Ищет в интернете через DuckDuckGo. Возвращает список результатов (может быть пустым)."""
    try:
        from duckduckgo_search import DDGS
        with DDGS() as ddgs:
            return list(ddgs.text(query, max_results=max_results))
    except Exception as e:
        print(f"[Ошибка поиска в интернете] {e}")
        return []


def answer_with_search(query):
    """Ищет в интернете и просит ИИ кратко ответить на основе найденного."""
    clean_query = query
    for trigger in SEARCH_TRIGGERS:
        clean_query = clean_query.replace(trigger, "")
    clean_query = clean_query.strip() or query

    speak("Ищу в интернете, сэр. Секунду...")
    results = web_search(clean_query)
    if not results:
        return "Не удалось найти информацию в интернете, сэр. Проверьте подключение."

    context_lines = ["Результаты поиска в интернете:"]
    for r in results:
        title = r.get("title", "")
        body = r.get("body", "")
        context_lines.append(f"- {title}: {body}")
    context = "\n".join(context_lines)

    if not client:
        return "Нашёл результаты, но ИИ-модуль не настроен, чтобы их обобщить, сэр."

    try:
        response = client.chat.completions.create(
            model="openai/gpt-oss-20b",
            messages=[
                {
                    "role": "system",
                    "content": (
                        f"Ты — {BOT_NAME}. Ниже приведены результаты поиска в интернете. Кратко "
                        "(3-5 предложений) ответь на вопрос пользователя, опираясь именно на эти "
                        "результаты. Если результаты противоречивы или недостаточны — скажи об "
                        "этом честно, не выдумывай."
                    ),
                },
                {"role": "user", "content": f"Вопрос: {clean_query}\n\n{context}"},
            ],
            temperature=0.3,
            max_tokens=1024,
        )
        return response.choices[0].message.content
    except Exception as e:
        print(f"[Ошибка Groq при обработке результатов поиска] {e}")
        return "Нашёл информацию в интернете, но не смог её обработать, сэр."


def ask_ai(prompt, mode="chat"):
    """mode: 'chat' — обычный короткий ответ,
    'study' — объяснение темы репетитором,
    'problem' — пошаговое решение задачи."""
    if not client:
        return "ИИ-модуль не настроен: отсутствует ключ GROQ_API_KEY, сэр."
    try:
        if mode == "study":
            system_prompt = (
                f"Ты — {BOT_NAME}, терпеливый репетитор по экономике и банковскому делу. "
                "Объясняй темы простым языком, разбивай объяснение на понятные шаги, приводи "
                "примеры. Отвечай подробно (5-10 предложений), но без лишней воды.\n\n"
                "КРИТИЧЕСКИ ВАЖНО — это учебный материал, ошибки недопустимы:\n"
                "- Называя даты, имена, цифры, названия законов или организаций — будь предельно "
                "точен. Если не уверен в точной дате или цифре, прямо скажи 'точную дату/цифру "
                "не помню, уточните в учебнике', вместо того чтобы придумывать.\n"
                "- Не путай похожие термины и события (например, разные банковские реформы или "
                "похожие по названию организации).\n"
                "- Если вопрос неоднозначен или в нём может быть ошибка — переспроси или укажи "
                "на это, прежде чем отвечать.\n"
                "- Лучше признать неуверенность, чем дать красивый, но неверный ответ.\n\n"
                f"{ECONOMIC_SOURCES}"
            )
            history = memory_store.study_history
        elif mode == "problem":
            system_prompt = (
                f"Ты — {BOT_NAME}, помощник по решению экономических и математических задач "
                "для студента экономического университета. Решай задачу строго по шагам:\n"
                "1) Кратко выпиши исходные данные из условия.\n"
                "2) Укажи, какую формулу нужно применить (напиши её явно).\n"
                "3) Подставь числа в формулу.\n"
                "4) Выполни вычисления по действиям, не пропускай шаги.\n"
                "5) Дай финальный ответ с единицами измерения (%, руб., шт. и т.п.), выдели его отдельно.\n"
                "Будь математически точен: пересчитывай арифметику перед тем, как дать ответ. "
                "Если данных в условии не хватает — прямо скажи, каких именно данных недостаёт."
            )
            history = memory_store.problem_history
        else:
            system_prompt = (
                f"Ты — {BOT_NAME}, умный и вежливый ИИ-ассистент. Отвечай кратко "
                "(1-2 предложения), по делу и с уважением к сэру."
            )
            history = None

        if history is not None:
            messages = [{"role": "system", "content": system_prompt}]
            messages.extend(history[-10:])
            messages.append({"role": "user", "content": prompt})
        else:
            messages = [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": prompt},
            ]

        response = client.chat.completions.create(
            model="openai/gpt-oss-20b",
            messages=messages,
            temperature=0.2 if mode == "problem" else 0.7,
            max_tokens=1536 if mode in ("study", "problem") else 512,
        )
        answer = response.choices[0].message.content

        if history is not None:
            memory_store.last_saved_question = prompt
            memory_store.last_saved_answer = answer
            history.append({"role": "user", "content": prompt})
            history.append({"role": "assistant", "content": answer})
            if len(history) > 60:
                del history[:2]
            memory_store.save_memory()

            # Автоматически сохраняем каждый учебный ответ в конспект — без команды "сохрани это"
            try:
                save_note(prompt, answer)
            except Exception as e:
                print(f"[Ошибка автосохранения конспекта] {e}")

        return answer
    except Exception as e:
        print(f"[Groq ошибка] {e}")
        return "Произошла ошибка связи с нейросетью, сэр."


